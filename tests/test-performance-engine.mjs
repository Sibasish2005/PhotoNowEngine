import path from 'path';
import fs from 'fs/promises';
import fsSync from 'fs';
import sharp from 'sharp';
import {
  analyzeSingleMediaAsset,
  analyzeWebAssets,
  testWebPerformance,
  comparePerformanceTests,
  generateOptimizationPlan,
  executeOptimizationPlan,
  verifyOptimization,
  groupDuplicates,
  formatMcpResponse,
  formatBytes,
  saveLocalReport,
} from '../lib/engine/index.mjs';

const TEST_SANDBOX = path.resolve('./tests/sandbox_performance');

async function setupSandbox() {
  await fs.rm(TEST_SANDBOX, { recursive: true, force: true });
  await fs.mkdir(TEST_SANDBOX, { recursive: true });

  // 1. Create an oversized photographic PNG (3000x2000 px)
  const oversizedPng = path.join(TEST_SANDBOX, 'hero_banner.png');
  await sharp({
    create: {
      width: 3000,
      height: 2000,
      channels: 3,
      background: { r: 180, g: 60, b: 30 },
    },
  })
    .png()
    .toFile(oversizedPng);

  // 2. Create a duplicate copy of hero_banner with slight crop
  const duplicatePng = path.join(TEST_SANDBOX, 'hero_banner_copy.png');
  await sharp(oversizedPng).png().toFile(duplicatePng);

  // 3. Create a legacy uncompressed JPEG (1600x1200 px)
  const legacyJpg = path.join(TEST_SANDBOX, 'product_shot.jpg');
  await sharp({
    create: {
      width: 1600,
      height: 1200,
      channels: 3,
      background: { r: 40, g: 120, b: 200 },
    },
  })
    .jpeg({ quality: 98 })
    .toFile(legacyJpg);

  // 4. Create an SVG file with embedded comment bloat
  const sampleSvg = path.join(TEST_SANDBOX, 'logo.svg');
  const svgContent = `<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200">
    <!-- Generated by Vector Tool v4.2 Metadata Block -->
    <!-- ${'A'.repeat(5000)} -->
    <rect width="200" height="200" fill="#10b981"/>
    <circle cx="100" cy="100" r="50" fill="#ffffff"/>
  </svg>`;
  await fs.writeFile(sampleSvg, svgContent, 'utf8');

  console.log(`✓ Synthetic performance test assets initialized in ${TEST_SANDBOX}`);
}

async function runTests() {
  console.log('\n===========================================================');
  console.log('🚀 RUNNING PHOTONOW WEBSITE PERFORMANCE INTELLIGENCE TESTS');
  console.log('===========================================================\n');

  await setupSandbox();

  // Test 1: Single Asset Analysis
  console.log('--- 1. Testing Media Analyzer (Single File) ---');
  const heroPath = path.join(TEST_SANDBOX, 'hero_banner.png');
  const singleAnalysis = await analyzeSingleMediaAsset(heroPath);
  console.log(`  ✓ File: ${singleAnalysis.fileName} (${singleAnalysis.dimensions}, ${singleAnalysis.sizeFormatted})`);
  console.log(`  ✓ Format: ${singleAnalysis.format}, Potential savings: ${formatBytes(singleAnalysis.optimizationPotentialBytes)}`);
  console.log(`  ✓ Issues identified (${singleAnalysis.issues.length}):`, singleAnalysis.issues.map((i) => i.id));
  if (!singleAnalysis.issues.some((i) => i.id === 'OVERSIZED_IMAGE')) {
    throw new Error('Expected OVERSIZED_IMAGE issue for 3000x2000 image');
  }
  if (!singleAnalysis.issues.some((i) => i.id === 'INEFFICIENT_FORMAT')) {
    throw new Error('Expected INEFFICIENT_FORMAT issue for photographic PNG');
  }
  console.log('  ✅ PASS: Media Analyzer accurately diagnosed single asset\n');

  // Test 2: Project Asset Audit
  console.log('--- 2. Testing Project Web Asset Audit ---');
  const projectAnalysis = await analyzeWebAssets(TEST_SANDBOX);
  console.log(`  ✓ Total Assets Scanned: ${projectAnalysis.totalAssets}`);
  console.log(`  ✓ Total Media Size: ${projectAnalysis.totalSizeFormatted}`);
  console.log(`  ✓ Potential Bandwidth Savings: ${projectAnalysis.potentialSavingsFormatted}`);
  console.log(`  ✓ PhotoNow Score: ${projectAnalysis.score.overall}/100`);
  console.log(`    - Format Efficiency: ${projectAnalysis.score.breakdown.formatEfficiency}/25`);
  console.log(`    - Image Sizing: ${projectAnalysis.score.breakdown.imageSizing}/25`);
  console.log(`    - Compression: ${projectAnalysis.score.breakdown.compression}/20`);
  console.log(`    - Responsive Readiness: ${projectAnalysis.score.breakdown.responsiveReadiness}/15`);
  console.log(`    - SVG Efficiency: ${projectAnalysis.score.breakdown.svgEfficiency}/15`);
  if (projectAnalysis.score.overall >= 100) {
    throw new Error('Score should have deductions for oversized/duplicate assets');
  }
  console.log('  ✅ PASS: Project audit evaluated 5-axis score & deductions\n');

  // Test 3: Perceptual Duplicate Detection
  console.log('--- 3. Testing Perceptual Duplicate Detection ---');
  console.log(`  ✓ Duplicate groups found: ${projectAnalysis.duplicateGroups.length}`);
  if (projectAnalysis.duplicateGroups.length === 0) {
    throw new Error('Expected at least 1 duplicate group for hero_banner and copy');
  }
  const group = projectAnalysis.duplicateGroups[0];
  console.log(`  ✓ Duplicate group files (${group.files.length}):`, group.files.map((f) => path.basename(f.path)));
  console.log(`  ✓ Similarity: ${group.similarityPercent}%, Potential savings: ${group.potentialSavingsFormatted}`);
  if (group.similarityPercent < 90) {
    throw new Error('Expected >=90% similarity between identical images');
  }
  console.log('  ✅ PASS: Perceptual duplicate detection passed\n');

  // Test 4: Web Performance Tester (Local Project Audit)
  console.log('--- 4. Testing Web Performance Tester ---');
  const perfTest = await testWebPerformance(TEST_SANDBOX);
  console.log(`  ✓ Test ID: ${perfTest.testId}`);
  console.log(`  ✓ Target: ${perfTest.target}`);
  console.log(`  ✓ Performance Score: ${perfTest.score.overall}/100`);
  console.log(`  ✓ Estimated 4G Mobile Transfer Time: ${perfTest.metrics.estimatedTransferTime4GMs}ms`);
  if (perfTest.metrics.lcpCandidate) {
    console.log(`  ✓ LCP Candidate: ${perfTest.metrics.lcpCandidate.pathOrUrl} (${perfTest.metrics.lcpCandidate.sizeFormatted})`);
  }
  console.log(`  ✓ Next Action: ${perfTest.nextAction}`);
  console.log('  ✅ PASS: Web Performance Tester completed\n');

  // Test 5: Optimization Plan Generation
  console.log('--- 5. Testing Optimization Plan Generator ---');
  const optPlan = await generateOptimizationPlan(TEST_SANDBOX, {
    format: 'webp',
    maxDimension: 1920,
    quality: 82,
  });
  console.log(`  ✓ Plan ID: ${optPlan.planId}`);
  console.log(`  ✓ Actions Count: ${optPlan.actionsCount}`);
  console.log(`  ✓ Estimated Reduction: ${optPlan.estimatedBeforeFormatted} -> ${optPlan.estimatedAfterFormatted} (${optPlan.estimatedReductionPercent} reduction)`);
  console.log(`  ✓ Actions impact summary: High: ${optPlan.impactSummary.high}, Med: ${optPlan.impactSummary.medium}, Low: ${optPlan.impactSummary.low}`);
  if (optPlan.actionsCount === 0) {
    throw new Error('Expected optimization actions to be generated');
  }
  console.log('  ✅ PASS: Optimization plan generated successfully\n');

  // Test 6: Optimization Execution (Safe & Non-Destructive)
  console.log('--- 6. Testing Web Performance Booster Execution ---');
  const execution = await executeOptimizationPlan(optPlan.planId);
  console.log(`  ✓ Processed: ${execution.totalProcessed}, Succeeded: ${execution.succeeded}, Failed: ${execution.failed}`);
  console.log(`  ✓ Actual Media Size: ${execution.actualBeforeFormatted} -> ${execution.actualAfterFormatted}`);
  console.log(`  ✓ Actual Saved: ${execution.actualSavedFormatted} (${execution.actualReductionPercent} savings)`);
  if (execution.succeeded === 0) {
    throw new Error('Expected at least 1 image optimization to succeed');
  }
  if (execution.failed > 0) {
    throw new Error(`Execution had ${execution.failed} failures`);
  }
  // Verify output files exist and are valid images
  for (const detail of execution.details) {
    if (detail.status === 'success') {
      const exists = fsSync.existsSync(detail.outputPath);
      if (!exists) throw new Error(`Output file not created: ${detail.outputPath}`);
      const meta = await sharp(detail.outputPath).metadata();
      if (!meta.width || !meta.height) throw new Error(`Invalid output image metadata for ${detail.outputPath}`);
    }
  }
  console.log('  ✅ PASS: Optimization executed safely, outputs verified\n');

  // Test 7: Verification & Local Reporting
  console.log('--- 7. Testing Verification & Local Reporting ---');
  const verification = await verifyOptimization(optPlan.planId);
  console.log(`  ✓ Reduction Measured: ${verification.reductionPercent}`);
  console.log(`  ✓ Score After: ${verification.scoreAfter}/100`);
  console.log('  ✓ Measured Improvements:', verification.measuredImprovements);

  const reportPath = await saveLocalReport(verification, 'html', path.join(TEST_SANDBOX, 'reports'));
  const reportMdPath = await saveLocalReport(verification, 'markdown', path.join(TEST_SANDBOX, 'reports'));
  console.log(`  ✓ Local HTML report generated: ${reportPath}`);
  console.log(`  ✓ Local Markdown report generated: ${reportMdPath}`);
  if (!fsSync.existsSync(reportPath) || !fsSync.existsSync(reportMdPath)) {
    throw new Error('Report files were not written to disk');
  }
  console.log('  ✅ PASS: Verification and local reporting passed\n');

  // Test 8: Token Efficiency & Progressive Disclosure
  console.log('--- 8. Testing Token Efficiency & Progressive Disclosure ---');
  const compactResp = formatMcpResponse({
    ok: true,
    summary: {
      score: 82,
      totalAssets: 45,
      totalSizeBytes: 12500000,
      potentialSavingsBytes: 8500000,
    },
    issues: ['hero.png: oversized', 'product.png: inefficient format', 'banner.png: duplicate'],
    recommendations: ['Convert to WebP', 'Downscale to 1920px'],
    detailLevel: 'compact',
    tokenBudget: 300,
  });
  console.log('  ✓ Compact response keys:', Object.keys(compactResp));
  console.log('  ✓ Compact summary:', JSON.stringify(compactResp.summary));
  console.log('  ✓ Next Action provided:', compactResp.nextAction);
  if (!compactResp.nextAction || !compactResp.summary?.score) {
    throw new Error('Compact response missing nextAction or score');
  }

  // Test budget truncation
  const hugeIssues = Array.from({ length: 100 }, (_, i) => `Issue ${i}: large file ${i}.png`);
  const budgetedResp = formatMcpResponse({
    ok: true,
    summary: { score: 70, totalAssets: 100 },
    issues: hugeIssues,
    detailLevel: 'detailed',
    tokenBudget: 150, // very tight token budget
  });
  const budgetedStr = JSON.stringify(budgetedResp);
  console.log(`  ✓ Budgeted response tokens: ~${Math.ceil(budgetedStr.length / 4)} (Budget was 150)`);
  if (budgetedStr.length > 150 * 4 + 200) {
    throw new Error('Token budget was not respected');
  }
  console.log('  ✅ PASS: Token efficiency and progressive disclosure verified\n');

  console.log('===========================================================');
  console.log('🎉 ALL 8 PERFORMANCE INTELLIGENCE TEST SUITES PASSED 100%!');
  console.log('===========================================================\n');
}

runTests().catch((err) => {
  console.error('\n❌ TEST FAILED:', err);
  process.exit(1);
});
